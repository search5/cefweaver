"""Emit cefweaver/types.py: the CEF enumerations and value types as Python types.

The module is plain Python (no compiled code) so that programs can use it, and type
checkers can read it, without CEF:

    from cefweaver import types
    types.MouseButtonType.LEFT        # an enum.IntEnum member, still an int
    types.EventFlags.SHIFT_DOWN | types.EventFlags.CONTROL_DOWN   # an enum.IntFlag
    types.Rect(0, 0, 640, 480)        # a typing.NamedTuple

CEF methods take and return these as plain integers and tuples, so anything that works
as an int or a tuple works for them.
"""

import re

from emit_cython import all_structs
from model import py_class_name

HEADER = '''"""The CEF enumerations and value types (see tools/gen/emit_types.py).

Enumerations (`enums.py`) are `enum.IntEnum` (or `enum.IntFlag` for bit flags), so a member can
be used wherever CEF wants an integer, and a value CEF reports that has no member is passed on
as a plain int. Value types (`structs.py`) are `typing.NamedTuple`: they unpack, and a tuple
with the same fields works wherever one is expected; every field has a default (zero, "" or
None, as in C++). Both are exported here: `types.MouseButtonType`, `types.Rect`.
"""
'''


def _docstring(text, indent):
    text = re.sub(r"\s+", " ", text).replace("\\", "\\\\").replace('"""', "'''").strip()
    if not text:
        return []
    pad = " " * indent
    return ['%s"""%s"""' % (pad, text)]


def _all_list(names):
    return ["", "", "__all__ = ["] + ['    "%s",' % n for n in sorted(names)] + ["]"]


def emit(model, banner):
    """The `cefweaver.types` package as {file name: text}: the enumerations (`enums.py`), the value types
    (`structs.py`) and `__init__.py`, which exports both."""
    head = ["# " + banner, "# GENERATED by tools/gen/generate.py. DO NOT EDIT.", ""]
    enums = ['"""The CEF enumerations (see tools/gen/emit_types.py)."""', "", "import enum"]
    enum_names = []
    for info in sorted(model.enum_defs.values(), key=lambda e: e.py_name):
        base = "enum.IntFlag" if info.flag else "enum.IntEnum"
        enums += ["", "", "class %s(%s):" % (info.py_name, base)]
        doc = _docstring(info.doc or "The CEF enumeration %s." % info.cname, 4)
        enums += doc
        for name, value in info.members:
            enums.append("    %s = %s" % (name, value if value >= 0 else "(%d)" % value))
        enum_names.append(info.py_name)

    body, struct_names, used = [], [], set()
    for cls, struct in all_structs(model).items():
        py = py_class_name(cls)
        body += ["", "", "class %s(NamedTuple):" % py]
        body += _docstring("The CEF value type %s. Anywhere one is expected, a tuple with the "
                           "same fields works too." % cls, 4)
        for f in struct.fields:
            if f.string:
                default = '""'
            elif f.time:
                default = "None"
            elif f.array:
                default = "()"  # an empty tuple of the elements
            elif f.struct:
                default = "%s()" % f.py
            else:
                default = {"bool": "False", "float": "0.0"}.get(f.py, "0")
            body.append("    %s: %s = %s" % (f.name, f.py, default))
            used.update(re.findall(r"\w+", f.py))
        struct_names.append(py)
    imports = sorted(used & set(enum_names))
    structs = ['"""The CEF value types (see tools/gen/emit_types.py)."""', "", "import datetime",
               "from typing import NamedTuple"]
    if imports:
        structs += ["", "from .enums import (%s)" % ", ".join(imports)]
    structs += body

    init = HEADER.rstrip("\n").split("\n")
    init += ["", "from . import enums, structs", "from .enums import *  # noqa: F401,F403",
             "from .structs import *  # noqa: F401,F403", "", "__all__ = enums.__all__ + structs.__all__"]
    return {
        "__init__.py": "\n".join(head + init) + "\n",
        "enums.py": "\n".join(head + enums + _all_list(enum_names)) + "\n",
        "structs.py": "\n".join(head + structs + _all_list(struct_names)) + "\n",
    }
