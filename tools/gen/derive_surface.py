"""Derive what java-cef exposes, as tools/gen/surface.py.

    python tools/gen/derive_surface.py /path/to/java-cef

What java-cef opens is the floor of cefweaver's API (the project decision: everything java-cef
opens is implemented the way java-cef does; more is allowed, and listed in the wiki as beyond
java-cef). java-cef's native code is the list: a library class has the JNI functions
`Java_org_cef_..._N_N_<Name>` of its `native/Cef<Class>_N.cpp`, and a handler the CEF methods its
`native/*_handler.cpp` overrides. The result is committed; this tool is only run to renew it.
"""

import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))

# java-cef's own class name -> the CEF class (handlers and callbacks that java-cef writes).
HANDLERS = {
    "CompletionCallback": "CefCompletionCallback",
    "CookieVisitor": "CefCookieVisitor",
    "PdfPrintCallback": "CefPdfPrintCallback",
    "RunFileDialogCallback": "CefRunFileDialogCallback",
    "StringVisitor": "CefStringVisitor",
    "ContextMenuHandler": "CefContextMenuHandler",
    "CookieAccessFilter": "CefCookieAccessFilter",
    "DevToolsMessageObserver": "CefDevToolsMessageObserver",
    "DialogHandler": "CefDialogHandler",
    "DisplayHandler": "CefDisplayHandler",
    "DownloadHandler": "CefDownloadHandler",
    "DragHandler": "CefDragHandler",
    "FocusHandler": "CefFocusHandler",
    "JSDialogHandler": "CefJSDialogHandler",
    "KeyboardHandler": "CefKeyboardHandler",
    "LifeSpanHandler": "CefLifeSpanHandler",
    "LoadHandler": "CefLoadHandler",
    "PrintHandler": "CefPrintHandler",
    "RenderHandler": "CefRenderHandler",
    "RequestContextHandler": "CefRequestContextHandler",
    "RequestHandler": "CefRequestHandler",
    "ResourceHandler": "CefResourceHandler",
    "ResourceRequestHandler": "CefResourceRequestHandler",
    "SchemeHandlerFactory": "CefSchemeHandlerFactory",
    "URLRequestClient": "CefURLRequestClient",
    "WriteHandler": "CefWriteHandler",
}
# CefBrowser, CefBrowserHost and CefFrame are one Java object each (CefBrowser_N, CefFrame_N):
# a method belongs to whichever of the three CEF classes has it.
MERGED = ("CefBrowser", "CefBrowserHost", "CefFrame")
# JNI functions that are not CEF methods (Java object management, creation by the Java side).
NOT_CEF = {"Dispose", "CreateBrowser", "CreateDevTools", "SetParent", "SetWindowVisibility",
           "UpdateUI", "CefRequestContext_1DTOR"}
# What java-cef's wrapper calls under another name.
RENAMED = {"SendMouseEvent": ("SendMouseClickEvent", "SendMouseMoveEvent"),
           "Close": ("CloseBrowser",)}


def derive(root):
    native = os.path.join(root, "native")
    surface = {}
    merged = set()
    for path in sorted(glob.glob(os.path.join(native, "Cef*_N.cpp"))):
        cls = os.path.basename(path)[:-6]
        text = open(path, encoding="utf-8", errors="replace").read()
        names = set(re.findall(r"Java_org_cef_\w+?_1N_N_1(\w+)\(", text)) - NOT_CEF
        for old, new in RENAMED.items():
            if old in names:
                names |= set(new)
        if cls in MERGED:
            merged |= names
        else:
            surface[cls] = names
    for cls in MERGED:
        surface[cls] = set(merged)
    for path in sorted(glob.glob(os.path.join(native, "*.cpp"))):
        if path.endswith("_N.cpp"):
            continue
        text = open(path, encoding="utf-8", errors="replace").read()
        for match in re.finditer(r"^[\w:<>\*&,\s]+?\b(\w+)::(\w+)\(", text, re.M):
            cls, method = match.groups()
            if cls in HANDLERS and cls != method:
                surface.setdefault(HANDLERS[cls], set()).add(method)
    # CefClient: the getters of the handlers (the rest of ClientHandler is the router's).
    handler = open(os.path.join(native, "client_handler.cpp"), encoding="utf-8").read()
    surface["CefClient"] = {m for m in set(re.findall(r"ClientHandler::(Get\w+Handler)\(", handler))
                            if m not in ("GetWindowHandler", "GetHandler")}
    return surface


def render(surface):
    out = ['"""What java-cef exposes: CEF class -> the CEF methods that java-cef opens.',
           "",
           "GENERATED by tools/gen/derive_surface.py from a java-cef checkout. cefweaver opens this",
           "and no more: `Scope` leaves every other method out and says so in the report.",
           '"""',
           "",
           "SURFACE = {"]
    for cls in sorted(surface):
        names = sorted(surface[cls])
        out.append('    "%s": frozenset({' % cls)
        line = "       "
        for name in names:
            piece = ' "%s",' % name
            if len(line) + len(piece) > 98:
                out.append(line)
                line = "       "
            line += piece
        out.append(line)
        out.append("    }),")
    out.append("}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(os.path.join(HERE, "surface.py"), "w", encoding="utf-8", newline="\n") as f:
        f.write(render(derive(sys.argv[1])))
    print("wrote tools/gen/surface.py")
