"""Emit the type stub (.pyi) of the compiled module."""

from emit_cython import (_annotation, _docstring, all_structs, public_function_name,
                         struct_tuple_annotation)
from model import py_class_name, py_param_name
from typesys import Buffer, Bytes, Planes, ClientRef, ItemBytes, Enum, LibRef, Struct, Vector, Void


def _value_annotation(kind):
    """A value type is also accepted as a plain tuple where Python hands it to CEF; an
    enumeration as a plain int."""
    if isinstance(kind, Enum):
        return "%s | int" % _annotation(kind) if kind.py else "int"
    return "%s | %s" % (_annotation(kind), struct_tuple_annotation(kind))


def _param_annotation(param, client_side):
    if isinstance(param.kind, Planes):
        return "list[memoryview]"
    if isinstance(param.kind, Buffer):
        return "memoryview"
    if isinstance(param.kind, (Bytes, ItemBytes)):
        return "bytes | bytearray | memoryview"
    if isinstance(param.kind, Vector) and not client_side:
        # Any sequence is accepted; a struct in it may be a plain tuple.
        element = param.kind.element
        return "Sequence[%s]" % (_value_annotation(element) if isinstance(element, Struct)
                                 else _annotation(element))
    if isinstance(param.kind, (Struct, Enum)) and not client_side:
        return _value_annotation(param.kind)
    text = _annotation(param.kind)
    # A library method accepts None only where the header says optional_param. A handler
    # gets None only for an object that CEF does not pass; strings, structs and lists are
    # always given (empty when there is nothing).
    nullable = param.optional and (not client_side or isinstance(param.kind, (LibRef, ClientRef)))
    return text + " | None" if nullable else text


def _return_annotation(plan, client_side):
    if client_side:
        parts = []
        for _, kind in plan.results:
            text = _value_annotation(kind) if isinstance(kind, (Struct, Enum)) else _annotation(kind)
            parts.append(text + " | None" if isinstance(kind, (LibRef, ClientRef)) else text)
        if not parts:
            return "None"
        return parts[0] if len(parts) == 1 else "tuple[%s]" % ", ".join(parts)
    if any(isinstance(p.kind, (Bytes, ItemBytes)) and p.out for p in plan.params):
        return "bytes"  # the return value is only the length of them
    text = _annotation(plan.ret)
    never_none = plan.static and plan.cef_name == "Create" and not any(
        isinstance(p.kind, Bytes) for p in plan.params)  # BinaryValue.create(b"") is None
    if isinstance(plan.ret, LibRef) and not never_none:
        text += " | None"  # CEF may return no object; a Create() factory never does
    if plan.outs:  # output parameters of a library method are returned after the return value
        parts = ([] if isinstance(plan.ret, Void) else [text]) + [_annotation(p.kind) for p in plan.outs]
        return parts[0] if len(parts) == 1 else "tuple[%s]" % ", ".join(parts)
    return text


def _stub(plan, client_side, indent, model, name=None, with_self=True):
    pad = " " * indent
    params = ([] if plan.static or not with_self else ["self"])
    for p in plan.params:
        if isinstance(p.kind, ItemBytes):
            size = py_param_name(p.size_name)
            if p.out:
                params += ["%s: int" % py_param_name(p.count_name), "%s: int = 1" % size]
            else:
                params += ["%s: bytes | bytearray | memoryview" % p.name, "%s: int = 1" % size]
        elif isinstance(p.kind, Bytes) and p.out:
            params.append("%s: int" % py_param_name(p.size_name))  # how much to read
        elif p in plan.ins:
            params.append("%s: %s" % (p.name, _param_annotation(p, client_side)))
    lines = []
    if plan.static and plan.owner:
        lines.append(pad + "@staticmethod")
    lines.append("%sdef %s(%s) -> %s:" % (pad, name or plan.name, ", ".join(params),
                                         _return_annotation(plan, client_side)))
    doc = _docstring(model.comment(plan.node), indent + 4)
    lines += doc if doc else [pad + "    ..."]
    if doc:
        lines.append(pad + "    ...")
    return lines


def emit(model, scope, plans_by_class, function_plans, handwritten, banner):
    all_plans = [p for plans in plans_by_class.values() for p in plans if p.supported]
    all_plans += [p for p in function_plans if p.supported]
    out = [
        "# " + banner,
        "# GENERATED by tools/gen/generate.py (with tools/gen/handwritten.pyi). DO NOT EDIT.",
        "",
        "from __future__ import annotations",
        "",
    ]
    out += handwritten.rstrip("\n").split("\n")
    out.append("")
    out.append("")

    # The enumerations and value types are defined in cefweaver/types.py. The value types are
    # also available as cefweaver.Rect and so on (`X as X` marks the re-export).
    enums = sorted({k.py for p in all_plans for k in [p.ret] + [q.kind for q in p.params]
                    if isinstance(k, Enum) and k.py})
    structs = [py_class_name(c) for c in all_structs(model)]
    if enums:
        out.append("from .types import (")
        out += ["    %s," % n for n in enums]
        out.append(")")
    out.append("from .types import (")
    out += ["    %s as %s," % (n, n) for n in structs]
    out.append(")")
    out.append("")
    out.append("")

    for cls in scope.library_classes + scope.client_classes:
        client = cls.is_client_side()
        out.append("class %s:" % py_class_name(cls.get_name()))
        doc = _docstring(model.comment(cls), 4)
        out += doc
        plans = [p for p in plans_by_class[cls.get_name()] if p.supported]
        if not plans and not doc:
            out.append("    ...")
        for plan in plans:
            if client and plan.static:
                continue
            out += _stub(plan, client, 4, model)
        out.append("")
        out.append("")

    for plan in function_plans:
        if plan.supported:
            out += _stub(plan, False, 0, model, name=public_function_name(plan.cef_name),
                         with_self=False)
            out.append("")
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"
